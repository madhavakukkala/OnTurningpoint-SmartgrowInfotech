import Link from 'next/link';
import Image from 'next/image';
import { ArrowUpRight } from 'lucide-react';
import { Container } from '@/components/ui/Layout';
import { Reveal, RevealGroup, RevealItem } from '@/components/ui/Reveal';
import { ContactBlock } from '@/components/ContactBlock';
import { company } from '@/content/company';
import { footerColumns } from '@/content/nav';
import { countries } from '@/content/countries';

/**
 * Footer — white ground.
 *
 * Inverted from the previous dark treatment, so every value is re-derived
 * rather than alpha-composited: link text uses the ink scale instead of
 * white/NN opacities, which keeps contrast predictable (the white-on-espresso
 * opacities do not have legible equivalents on a light background).
 *
 * The closing wordmark stays solid rather than becoming a faint watermark —
 * on white it reads as a deliberate typographic sign-off, which is the effect
 * the reference uses. It is sized in `vw` so it always spans the container.
 * `aria-hidden` because it is decorative; the accessible brand name is carried
 * by the logo link in the nav and the copyright line below.
 */
export function Footer() {
  const year = new Date().getFullYear();
  const legalLinks = footerColumns.find((c) => c.title === 'Legal')?.links ?? [];

  return (
    <footer className="relative overflow-hidden border-t border-line bg-bg text-ink">
      <Container className="pb-10 pt-20 md:pt-28">
        {/* ---- Top: statement + link columns ---- */}
        <div className="grid gap-14 lg:grid-cols-12 lg:gap-10">
          <Reveal className="lg:col-span-5">
            {/* Dark mark now that the ground is white — the white variant is
                still generated by `npm run logo` for any dark section. */}
            <Link
              href="/"
              className="mb-8 inline-flex items-center gap-2.5"
              aria-label={`${company.name} — home`}
            >
              <Image src="/logo/logo-mark.svg" alt="" width={22} height={28} className="h-7 w-auto" />
              <span className="text-[0.9375rem] font-semibold tracking-[-0.5px] text-ink">
                {company.name}
              </span>
            </Link>

            <p className="max-w-sm text-[1.625rem] font-bold leading-[1.25] tracking-[-0.5px] text-ink">
              Your turning point <span className="accent font-normal text-ink-muted">starts here.</span>
            </p>
            <Link
              href="/contact"
              className="group mt-8 inline-flex items-center gap-2 rounded-pill bg-primary px-6 py-3 text-sm font-semibold text-white shadow-subtle transition-all duration-300 ease-brand hover:bg-primary-soft motion-safe:hover:-translate-y-0.5"
            >
              {company.primaryCta}
              <ArrowUpRight
                aria-hidden="true"
                size={15}
                strokeWidth={2}
                className="transition-transform duration-300 ease-brand group-hover:-translate-y-0.5 group-hover:translate-x-0.5"
              />
            </Link>
          </Reveal>

          <nav aria-label="Footer" className="lg:col-span-7">
            <RevealGroup className="grid grid-cols-2 gap-x-8 gap-y-10 sm:grid-cols-4" step={0.05}>
              {footerColumns.map((col) => (
                <RevealItem key={col.title}>
                  <h2 className="text-eyebrow font-semibold uppercase text-ink-subtle">{col.title}</h2>
                  <ul className="mt-4 space-y-2.5">
                    {col.links.map((link) => (
                      <li key={link.href}>
                        <Link
                          href={link.href}
                          className="text-[0.8125rem] text-ink-muted transition-colors duration-300 hover:text-ink"
                        >
                          {link.label}
                        </Link>
                      </li>
                    ))}
                  </ul>
                </RevealItem>
              ))}
            </RevealGroup>
          </nav>
        </div>

        {/* ---- Contact ---- */}
        <Reveal className="mt-20 border-t border-line pt-12">
          <ContactBlock className="lg:grid-cols-4" />
        </Reveal>

        {/* ---- Destinations ---- */}
        <Reveal className="mt-14">
          <h2 className="text-eyebrow font-semibold uppercase text-ink-subtle">Destinations</h2>
          <ul className="mt-4 flex flex-wrap gap-x-5 gap-y-2">
            {countries.map((c) => (
              <li key={c.slug}>
                <Link
                  href={`/countries/${c.slug}`}
                  className="text-[0.8125rem] text-ink-muted transition-colors duration-300 hover:text-ink"
                >
                  {c.name}
                </Link>
              </li>
            ))}
          </ul>
        </Reveal>

        {/* ---- Small print ---- */}
        <div className="mt-20 flex flex-col gap-4 border-t border-line pt-8 text-[0.75rem] text-ink-subtle md:flex-row md:items-center md:justify-between">
          <p>
            © {year} {company.name}. All rights reserved.
          </p>
          <ul className="flex flex-wrap gap-x-5 gap-y-2">
            {legalLinks.map((link) => (
              <li key={link.href}>
                <Link href={link.href} className="transition-colors duration-300 hover:text-ink">
                  {link.label}
                </Link>
              </li>
            ))}
          </ul>
        </div>
      </Container>

      {/* ---- Closing wordmark ---- */}
      <Reveal className="select-none px-4 md:px-8">
        <span
          aria-hidden="true"
          /* The one place tracking stays proportional rather than -1px. At up to
             248px, a flat -1px is ~0.4% of the em and reads LOOSER than default —
             the opposite of the packed setting used everywhere else. -0.045em
             keeps the wordmark visually as tight as the rest of the site. */
          className="mx-auto block max-w-container text-center font-bold leading-[0.78] tracking-[-0.045em] text-ink"
          style={{ fontSize: 'clamp(3.5rem, 15.1vw, 15.5rem)' }}
        >
          {company.name}
        </span>
      </Reveal>
    </footer>
  );
}
